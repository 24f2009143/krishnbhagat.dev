#!/usr/bin/env python3
"""Build a PYQ pack file from its source in tests/packs/, filling bank text verbatim:
__STEM_<id>__, __OPTIONS_<id>__ and __PARENT_<id>__ (the comprehension parent {id, text} of child <id>).
Usage: python3 -I tests/build_pack.py BANK.md tests/packs/<exam>/<file>.src.js  -> js/data/pyqs/<exam>/<file>.js"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from parse_mad1_q2 import parse  # noqa: E402

bank, src = sys.argv[1], sys.argv[2]
recs = {r["id"]: r for r in parse(bank, 1, 6673)}
text = open(src, encoding="utf-8").read()


def fill(m):
    kind, qid = m.group(1), m.group(2)
    r = recs[qid]
    if kind == "STEM":
        v = r["stem"]
    elif kind == "OPTIONS":
        v = [o["text"] for o in r["options"]]
    elif kind == "FIG":
        v = r["figureNote"]
    else:
        v = r["parent"]
    return json.dumps(v, ensure_ascii=False)


out = re.sub(r"__(STEM|OPTIONS|PARENT|FIG)_(\d+)__", fill, text)


def meta(m):
    r = recs[m.group(1)]
    mk = r["marks"]
    return '{id:"%s",paper:%s,date:%s,qno:%d,marks:%s,' % (r["id"], json.dumps(r["date"]), json.dumps(r["date"]), r["qno"], int(mk) if mk == int(mk) else mk)


# paper, date, question number and marks always come from the bank, never from typing
out, n = re.subn(r'\{id:"(\d+)",paper:"[^"]*",date:"[^"]*",qno:\d+,marks:[\d.]+,', meta, out)
exam = os.path.basename(os.path.dirname(src))
dst = os.path.join(HERE, "..", "js", "data", "pyqs", exam, os.path.basename(src).replace(".src.js", ".js"))
open(dst, "w", encoding="utf-8").write("/* GENERATED by tests/build_pack.py from " + os.path.relpath(src, os.path.join(HERE, "..")) + ": bank text is filled in verbatim. Edit the source, not this file. */\n" + out)
print("wrote", os.path.relpath(dst, os.path.join(HERE, "..")), len(out), "bytes;", n, "records take paper, date, qno and marks from the bank")
