#!/usr/bin/env node
/* Generate js/counts.js from the packs (totals are never typed by hand). --check exits 1 if the file is stale. */
"use strict";
const fs = require("fs"), path = require("path");
const { loadData, ROOT } = require("./load_data");
const { APP } = loadData();
const out = "/* GENERATED by tests/gen_counts.js from the PYQ packs. Do not edit. */\nAPP.counts=" + JSON.stringify(APP.liveCounts()) + ";\n";
const f = path.join(ROOT, "js/counts.js");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "";
  if (cur !== out) { console.log("counts.js is stale: run node tests/gen_counts.js"); process.exit(1); }
  console.log("counts.js is current"); process.exit(0);
}
fs.writeFileSync(f, out);
console.log("counts.js written:", JSON.stringify(APP.liveCounts().exams).slice(0, 200));
