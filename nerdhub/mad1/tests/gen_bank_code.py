#!/usr/bin/env python3
"""Write tests/bank_code_q2.py: every code block of every Quiz 2 PYQ stem (and comprehension parent), verbatim,
so assertions run the bank's own code. Usage: python3 -I tests/gen_bank_code.py BANK.md"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from parse_mad1_q2 import parse  # noqa: E402
FENCE = re.compile(r"```[\w]*\n(.*?)\n\s*```", re.S)
code = {}
for r in parse(sys.argv[1], 1, 6673):
    code[r["id"]] = [b.rstrip() + "\n" for b in FENCE.findall(r["stem"])]
    if r.get("parent"):
        code["parent:" + r["parent"]["id"]] = [b.rstrip() + "\n" for b in FENCE.findall(r["parent"]["text"])]
with open(os.path.join(HERE, "bank_code_q2.py"), "w", encoding="utf-8") as f:
    f.write('"""GENERATED by tests/gen_bank_code.py: code blocks of the Quiz 2 bank, verbatim. CODE[id] = [block, ...]."""\nCODE = {\n')
    for k in code:
        f.write("    %r: %r,\n" % (k, code[k]))
    f.write("}\n")
print(len(code), "entries,", sum(len(v) for v in code.values()), "code blocks")
